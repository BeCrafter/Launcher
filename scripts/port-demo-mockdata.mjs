#!/usr/bin/env node
// 从冻结的 demo 原型生成 MOCK_DATA 数据模块(逐字节一致):
//   node scripts/port-demo-mockdata.mjs
// 产出:src/renderer/src/data/mock/mock-data.ts
// 只读 demo;demo 数据变更后重跑本脚本即可再生成。
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import vm from 'node:vm'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const DEMO_DATA = join(ROOT, 'docs/demo/js/data.js')
const OUT = join(ROOT, 'src/renderer/src/data/mock/mock-data.ts')

// 同 check.mjs 手法:vm 沙箱打桩 localStorage,取顶层 MOCK_DATA
const ctx = {}
vm.createContext(ctx)
vm.runInContext(
  'const localStorage = { getItem: () => null, setItem: () => {}, removeItem: () => {} };',
  ctx
)
vm.runInContext(readFileSync(DEMO_DATA, 'utf8') + '\nthis.MOCK_DATA = MOCK_DATA;', ctx)
const M = ctx.MOCK_DATA

const body = `// GENERATED by scripts/port-demo-mockdata.mjs — 勿手改;源:docs/demo/js/data.js @ 06ff9ba
// mock 数据单一事实来源;组件禁止直接 import,须经 data/ 接缝(src/renderer/src/data/index.ts)

import type {
  Agent,
  AgentForm,
  AppMeta,
  AppUrls,
  CronJob,
  CronPreset,
  DrawerStatusModel,
  InvalidPlist,
  LogLine,
  OpsState,
  PortService
} from '@shared/models'

export interface MockData {
  meta: AppMeta
  urls: AppUrls
  agents: Agent[]
  invalidPlists: InvalidPlist[]
  crons: CronJob[]
  services: PortService[]
  brewServices: string[]
  aiAgents: { id: string; name: string; cli: string; version: string; path: string | null; status: 'installed' | 'not_found'; descKey: string; tags: string[]; icon: string }[]
  aiSkills: { id: string; nameKey: string; descKey: string; tag: string; icon: string }[]
  cronPresets: CronPreset[]
  liveLogs: [LogLine['type'], string][]
  drawer: {
    title: string
    scope: string
    opsState: OpsState
    form: AgentForm
    status: DrawerStatusModel
    logLines: [string, LogLine['type'], string][]
    xml: string
  }
}

export const MOCK_DATA: MockData = ${JSON.stringify(M, null, 2)}

// demo data.js 末尾的 URL 别名(原样保留)
export const GITHUB_REPO_URL: string = MOCK_DATA.urls.github
export const HELP_URL: string = MOCK_DATA.urls.help
`

writeFileSync(OUT, body, 'utf8')
console.log(`✓ mock-data.ts(${Object.keys(M).length} 顶层键)`)
