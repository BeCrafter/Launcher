let currentLang = localStorage.getItem('launcherLanguage') || 'zh-CN';
let currentModule = 'agents'; // 当前模块，语言切换时据此重建顶栏/列表

function t(key) {
  const dict = I18N[currentLang] || I18N['zh-CN'];
  return (dict && dict[key] !== undefined) ? dict[key] : key;
}

function fmt(template, vars) {
  return String(template).replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined ? vars[k] : m));
}

// 应用当前语言：重写静态 data-* 节点 → 按当前模块重建顶栏 → 重渲染各列表 → 同步状态栏
function applyLanguage() {
  currentLang = localStorage.getItem('launcherLanguage') || 'zh-CN';
  document.documentElement.lang = currentLang;
  document.querySelectorAll('[data-i18n]').forEach(el => {
    el.textContent = t(el.getAttribute('data-i18n'));
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    el.setAttribute('placeholder', t(el.getAttribute('data-i18n-placeholder')));
  });
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    el.setAttribute('title', t(el.getAttribute('data-i18n-title')));
  });
  const langSel = document.getElementById('languageSelect');
  if (langSel) langSel.value = currentLang;
  if (typeof switchModule === 'function') {
    switchModule(currentModule);            // 重建面包屑 + 顶栏按钮/占位符
  }
  renderAgents(activeFilter || 'all', (document.getElementById('globalSearch') || {}).value || '');
  renderCron();
  renderServices();
  updateModuleStatusBar(currentModule);
  // 抽屉操作栏若已打开，刷新其按钮/状态文案
  const drawerOpen = document.getElementById('editAgentFloat');
  if (drawerOpen && drawerOpen.classList.contains('open') && typeof updateOpsBar === 'function') {
    updateOpsBar();
  }
}
